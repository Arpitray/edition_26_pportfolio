// Downloads the Toolkit's technology logos from Simple Icons (https://simpleicons.org; the
// icon data is CC0, the logos remain their owners' trademarks) and writes them into
// src/content/toolIcons.ts as plain path data, so the site needs no icon package or CDN.
//
//   node fetch-icons.mjs
import { writeFileSync } from "node:fs";

const VERSION = "13.21.0";
const SLUGS = [
  "typescript", "react", "nextdotjs", "nodedotjs", "python", "fastapi", "postgresql", "supabase",
  "firebase", "cloudflareworkers", "cloudflare", "sanity", "googlechrome", "onnx", "langchain",
  "pandas", "scikitlearn", "posthog", "greensock", "threedotjs", "tailwindcss", "docker", "git", "github",
];

const icons = {};
for (const slug of SLUGS) {
  const res = await fetch(`https://cdn.jsdelivr.net/npm/simple-icons@${VERSION}/icons/${slug}.svg`);
  if (!res.ok) throw new Error(`${slug}: ${res.status}`);
  const svg = await res.text();
  const path = svg.match(/<path d="([^"]+)"/)?.[1];
  if (!path) throw new Error(`${slug}: no path`);
  icons[slug] = path;
  console.log(slug, path.length);
}

const body = Object.entries(icons).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
writeFileSync("../src/content/toolIcons.ts", `// Generated by tools/fetch-icons.mjs from Simple Icons ${VERSION} (CC0 icon data; the logos
// are trademarks of their owners). Each is one SVG path in a 24 x 24 box.
export const TOOL_ICONS = {
${body}
} as const;

export type ToolIcon = keyof typeof TOOL_ICONS;
`);
console.log("written", Object.keys(icons).length);
